// Requires a new seed_auth_check.py fixture with SIGNOFF_SEED_SECURITY_HISTORY=1.
import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.SIGNOFF_PLAYWRIGHT_MODULE ?? process.argv[2] ?? 'playwright');
const fixture = JSON.parse(await readFile(process.env.SIGNOFF_AUTH_FIXTURE, 'utf8'));
const base = process.env.SIGNOFF_TEST_UI;
assert.equal(new URL(base).hostname, '127.0.0.1');
const output = '/private/tmp/signoff-admin-security-check';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, timezoneId: 'Asia/Seoul' });
  const page = await context.newPage();
  page.setDefaultTimeout(10000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.name));
  await page.goto(`${base}/`);
  await page.getByRole('textbox', { name: '사용자 이름', exact: true }).fill('qa-admin');
  await page.getByLabel('비밀번호', { exact: true }).fill(fixture.password);
  await page.getByRole('button', { name: '로그인', exact: true }).click();
  await page.getByRole('link', { name: '보안 이력 관리', exact: true }).click();
  const initialCount = (await (await context.request.get(`${base}/api/auth/admin/security-events?limit=100`)).json()).items.length;
  assert.ok(initialCount > 25 && initialCount <= 50);
  const results = page.getByRole('region', { name: '전체 계정 보안 이력', exact: true });
  await results.getByText('표시된 이력 25개', { exact: true }).waitFor();
  await results.getByRole('button', { name: '이전 이력 보기', exact: true }).click();
  await results.getByText(`표시된 이력 ${initialCount - 25}개`, { exact: true }).waitFor();
  assert.ok(new URL(page.url()).searchParams.has('before_id'));
  await page.reload();
  await results.getByText(`표시된 이력 ${initialCount - 25}개`, { exact: true }).waitFor();
  await results.getByRole('button', { name: '최신 이력 보기', exact: true }).click();
  await results.getByText('표시된 이력 25개', { exact: true }).waitFor();
  await page.getByLabel('대상 계정 이름 (정확히)', { exact: true }).fill('qa-editor');
  await page.getByRole('button', { name: '검색', exact: true }).click();
  await page.getByLabel('작업 종류', { exact: true }).selectOption('password_reset');
  await page.getByLabel('실행 경로', { exact: true }).selectOption('operator');
  await results.getByText('표시된 이력 25개', { exact: true }).waitFor();
  assert.equal(await results.getByText('대상: qa-editor', { exact: true }).count(), 25);
  await results.getByRole('button', { name: '이전 이력 보기', exact: true }).click();
  await results.getByText('표시된 이력 5개', { exact: true }).waitFor();
  await page.reload();
  await results.getByText('표시된 이력 5개', { exact: true }).waitFor();
  assert.equal(await page.getByLabel('대상 계정 이름 (정확히)', { exact: true }).inputValue(), 'qa-editor', page.url());
  const startInput = page.getByLabel('시작 시각 (포함)', { exact: true });
  const endInput = page.getByLabel('종료 시각 (미포함)', { exact: true });
  await startInput.fill('2020-01-01T00:00:00.123');
  await endInput.fill('2030-01-01T00:00');
  await page.getByRole('button', { name: '검색', exact: true }).click();
  await results.getByText('표시된 이력 25개', { exact: true }).waitFor();
  const period = new URL(page.url()).searchParams;
  assert.equal(period.get('created_from'), '2019-12-31T15:00:00.123Z');
  assert.equal(period.get('created_before'), '2029-12-31T15:00:00.000Z');
  assert.equal(period.has('before_id'), false);
  await page.reload();
  await results.getByText('표시된 이력 25개', { exact: true }).waitFor();
  assert.equal(await startInput.inputValue(), '2020-01-01T00:00:00.123');
  assert.equal(await endInput.inputValue(), '2030-01-01T00:00');
  await results.getByRole('button', { name: '이전 이력 보기', exact: true }).click();
  await results.getByText('표시된 이력 5개', { exact: true }).waitFor();
  const appliedUrl = page.url();
  await endInput.fill('2010-01-01T00:00');
  await page.getByRole('button', { name: '검색', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '종료 시각은 시작 시각보다 늦어야 합니다.' }).waitFor();
  assert.equal(page.url(), appliedUrl);
  await results.getByText('표시된 이력 5개', { exact: true }).waitFor();
  await page.getByRole('button', { name: '검색 초기화', exact: true }).click();
  assert.equal(await startInput.inputValue(), '');
  assert.equal(await endInput.inputValue(), '');
  assert.equal(new URL(page.url()).search, '');
  await page.getByLabel('작업 종류', { exact: true }).selectOption('all_sessions_revoked');
  await results.getByText('대상: 전체 계정 (전역 작업)', { exact: true }).waitFor();
  await results.getByText('종료한 세션 기록: 7개', { exact: true }).waitFor();
  for (const width of [320, 390, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  }
  await page.setViewportSize({ width: 320, height: 900 });
  await page.locator('main').screenshot({ path: `${output}/global-event-mobile.png` });
  await page.getByLabel('대상 계정 이름 (정확히)', { exact: true }).fill('qa-editor');
  await page.getByRole('button', { name: '검색', exact: true }).click();
  await results.getByText('조건에 맞는 보안 이력이 없습니다.', { exact: true }).waitFor();
  await page.goto(`${base}/admin/security-events?action=unknown`);
  await results.getByRole('alert').waitFor();
  await page.getByRole('button', { name: '검색 초기화', exact: true }).click();
  await results.getByText('표시된 이력 25개', { exact: true }).waitFor();
  const owner = await browser.newContext();
  const login = await owner.request.post(`${base}/api/auth/login`, { headers: { 'X-Signoff-Client': '1' }, data: { username: 'qa-owner', password: fixture.password } });
  assert.equal(login.status(), 200);
  assert.equal((await owner.request.get(`${base}/api/auth/admin/security-events`)).status(), 403);
  const ownerPage = await owner.newPage();
  await ownerPage.goto(`${base}/admin/security-events`);
  await ownerPage.getByRole('alert').filter({ hasText: '관리자 계정으로 로그인' }).waitFor();
  assert.equal(await ownerPage.getByRole('link', { name: '보안 이력 관리', exact: true }).count(), 0);
  const anonymous = await browser.newContext();
  for (const username of ['qa-editor', 'qa-unregistered']) {
    const rejected = await anonymous.request.post(`${base}/api/auth/login`, { headers: { 'X-Signoff-Client': '1' }, data: { username, password: 'wrong-qa-password' } });
    assert.equal(rejected.status(), 401);
  }
  await page.getByLabel('작업 종류', { exact: true }).selectOption('login_failed');
  await results.getByText('표시된 이력 2개', { exact: true }).waitFor();
  assert.equal(await results.getByText('실행: 인증되지 않은 요청 · 서비스 API', { exact: true }).count(), 2);
  await results.getByText('입력된 이름 · 해당 시점에 등록된 계정 없음', { exact: true }).waitFor();
  await page.locator('main').screenshot({ path: `${output}/failed-logins-mobile.png` });
  const editor = await browser.newContext();
  assert.equal((await editor.request.post(`${base}/api/auth/login`, { headers: { 'X-Signoff-Client': '1' }, data: { username: 'qa-editor', password: fixture.password } })).status(), 200);
  const editorPage = await editor.newPage();
  await editorPage.goto(`${base}/account`);
  const personal = editorPage.getByRole('region', { name: '계정 보안 이력', exact: true });
  await personal.getByText('로그인 실패', { exact: true }).waitFor();
  await personal.getByText('실행: 인증되지 않은 요청', { exact: true }).waitFor();
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ result: 'PASS', checks: ['admin navigation', 'cursor pagination', 'filters and URL reload', 'global event', 'empty state', 'invalid filter recovery', 'project owner denied', 'failed login filter', 'unverified actor and unknown target', 'personal failed login history', '320/390/1440 width'], output }));
} finally { await browser.close(); }
