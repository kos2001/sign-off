// New disposable authenticated fixture only; see docs/report-import.md.
import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const { chromium } = await import(process.env.SIGNOFF_PLAYWRIGHT_MODULE ?? process.argv[2] ?? 'playwright');
const fixture = JSON.parse(await readFile(process.env.SIGNOFF_AUTH_FIXTURE, 'utf8'));
const base = process.env.SIGNOFF_TEST_UI;
assert.equal(new URL(base).hostname, '127.0.0.1');
const output = '/private/tmp/signoff-import-check';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const arrival = 1.23456789012345e-12;
const source = '\ufeff' + JSON.stringify({ checks: [{ type: 'check', path_type: 'max', path_group: 'clk', startpoint: 'launch/Q', endpoint: 'capture/D', source_path: [{ pin: 'launch/Q', arrival }, { pin: 'capture/D' }], slack: -1e-17 }] }, null, 2) + '\r\n';
const errors = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.setDefaultTimeout(10000);
  page.on('pageerror', e => errors.push(e.name));
  await page.route('**/api/agents/review/gate', route => route.fulfill({ json: { a5: null, v: null } }));
  await page.goto(`${base}/projects/${fixture.project}`);
  await page.getByRole('textbox', { name: '사용자 이름', exact: true }).fill('qa-editor');
  await page.getByLabel('비밀번호', { exact: true }).fill(fixture.password);
  await page.getByRole('button', { name: '로그인', exact: true }).click();
  await page.getByRole('link', { name: '보고서 가져오기', exact: true }).click();
  await page.getByLabel('OpenSTA 버전', { exact: true }).fill('QA synthetic');
  await page.getByLabel('설계 리비전', { exact: true }).fill('rev-browser');
  await page.getByLabel('시나리오 / 코너', { exact: true }).fill('ss-synthetic');
  await page.getByLabel('보고서 JSON', { exact: true }).fill('{broken');
  await page.getByRole('button', { name: '가져오기 미리보기', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'invalid JSON report' }).waitFor();
  const underflow = source.replace('-1e-17', '-1e-400');
  assert.notEqual(underflow, source);
  await page.getByLabel('보고서 JSON', { exact: true }).fill(underflow);
  const entered = await page.getByLabel('보고서 JSON', { exact: true }).inputValue();
  await page.getByRole('button', { name: '가져오기 미리보기', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'supported floating-point range' }).waitFor();
  assert.equal(await page.getByLabel('보고서 JSON', { exact: true }).inputValue(), entered);
  assert.equal(await page.getByRole('button', { name: '런으로 저장', exact: true }).count(), 0);
  await page.getByLabel('JSON 파일 선택', { exact: true }).setInputFiles({ name: 'timing.json', mimeType: 'application/json', buffer: Buffer.from(source) });
  await page.getByRole('button', { name: '가져오기 미리보기', exact: true }).click();
  const preview = page.getByRole('region', { name: '가져오기 미리보기', exact: true });
  await preview.getByText('경로 1개 · 위반 1개 · 제약 없음 0개', { exact: true }).waitFor();
  await preview.getByText('보고된 최악 슬랙: -0.00001 ps', { exact: true }).waitFor();
  await preview.getByText('-0.00001 ps', { exact: true }).waitFor();
  // Any metadata edit invalidates the preview before save.
  await page.getByLabel('설계 리비전', { exact: true }).fill('rev-browser-updated');
  assert.equal(await page.getByRole('button', { name: '런으로 저장' }).count(), 0);
  await page.getByRole('button', { name: '가져오기 미리보기', exact: true }).click();
  await preview.waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: `${output}/preview-mobile.png`, fullPage: true });
  await page.getByRole('button', { name: '런으로 저장', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '보고서와 근거를 저장했습니다.' }).waitFor();
  const runs = await (await context.request.get(`${base}/api/projects/${fixture.project}/runs`)).json();
  const run = runs.findLast(r => r.evidence_source === 'opensta_report');
  assert.ok(run?.result_locked);
  assert.equal(run.status, 'failed');
  await page.getByRole('link', { name: '저장한 런 보기', exact: true }).click();
  const row = page.getByRole('listitem', { name: `런 #${run.id}`, exact: true });
  assert.equal(await row.getByRole('button', { name: 'Pass', exact: true }).isEnabled(), false);
  await row.getByRole('button', { name: '실행 근거 보기', exact: true }).click();
  await row.getByText('업로드: qa-editor', { exact: true }).waitFor();
  await row.getByText('원본 보고서', { exact: true }).click();
  assert.equal(await row.getByLabel('OpenSTA 원본 보고서').textContent(), source);
  const downloadPromise = page.waitForEvent('download');
  await row.getByRole('button', { name: '근거 JSON 다운로드', exact: true }).click();
  const downloaded = await downloadPromise;
  const evidence = JSON.parse(await readFile(await downloaded.path(), 'utf8'));
  assert.equal(evidence.source_text, source);
  assert.equal(evidence.source_sha256, createHash('sha256').update(source).digest('hex'));
  assert.equal(evidence.design_revision, 'rev-browser-updated');
  assert.equal(evidence.result.metrics.worst_reported_slack_ps, -0.00001);
  await page.screenshot({ path: `${output}/evidence-mobile.png`, fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await row.getByRole('link', { name: '타이밍 경로', exact: true }).click();
  await page.getByRole('region', { name: '타이밍 경로 목록', exact: true }).getByText('그룹 clk · -0.00001 ps', { exact: true }).waitFor();
  await page.getByRole('button', { name: /경로 #1 ·/ }).click();
  const detail = page.getByRole('region', { name: '선택한 타이밍 경로', exact: true });
  await detail.getByText(`도착: ${arrival * 1e12} ps · 슬루: 미보고 / 유효한 값 없음`, { exact: true }).waitFor();
  await detail.getByText(/슬랙: -0\.00001 ps/).waitFor();
  for (const width of [320, 390, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  }
  await page.setViewportSize({ width: 320, height: 900 });
  await detail.screenshot({ path: `${output}/precision-detail-mobile.png` });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ result: 'PASS', checks: ['invalid JSON', 'underflow rejection and input retained', 'file upload', 'preview invalidation', 'units and tiny negative slack', 'save', 'locked result', 'uploader', 'original and download hash', 'path and pin precision', '320/390/1440 width'], output }));
} finally { await browser.close(); }
